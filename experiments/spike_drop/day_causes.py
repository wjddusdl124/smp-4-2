def main():
    d, g = DF.만들기()
    h = pd.read_csv(os.path.join(ROOT, 'data', 'processed', 'smp_dataset_hourly.csv'), usecols=['date', 'holiday_name'])
    hol = h.dropna().drop_duplicates('date').set_index('date')['holiday_name']
    p = pd.read_csv(os.path.join(ROOT, 'data', 'external', 'powersource_hourly.csv'))
    sol = p[p.hour_n.isin([12, 13, 14])].groupby('date')['solar_all'].mean() / 1000
    prev = g['drop'].shift(1)
    DOW = '월화수목금토일'

    t = pd.read_csv(os.path.join(OUT, 'drop_days_final.csv'))
    out = []
    for dt in t['date']:
        if dt in DROP_NOTE: out.append(DROP_NOTE[dt]); continue
        name = hol.get(dt)
        kind = {'설날': '설 연휴', '추석': '추석 연휴', '1월1일': '신정'}.get(name, f'{DOW[pd.Timestamp(dt).dayofweek]}요일') if name or pd.Timestamp(dt).dayofweek >= 5 else '휴일'
        s = f"{kind} 한낮 수요 감소({g.loc[dt, 'f_mid'] / 1000:.1f}GW)"
        if dt in sol.index: s += f" + 태양광 {sol[dt]:.1f}GW"
        if prev.get(dt) == 1: s += ', 전날 급락에 이어 연속'
        out.append(s)
    t['원인 (추정)'] = out
    t.to_csv(os.path.join(OUT, 'drop_days_final.csv'), index=False, encoding='utf-8')

    s = pd.read_csv(os.path.join(OUT, 'spike_days_final.csv'))
    s['원인 (추정)'] = s['date'].map(SPIKE_NOTE).fillna('')
    s.to_csv(os.path.join(OUT, 'spike_days_final.csv'), index=False, encoding='utf-8')
    print(t[['date', '원인 (추정)']].to_string(index=False)); print(s[['date', '원인 (추정)']].to_string(index=False))


if __name__ == '__main__':
    main()
